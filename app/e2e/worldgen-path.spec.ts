/**
 * The Phase 3 worldgen path (plan D5), driven only through dialogs, menus, Studios and the
 * command palette: a new project from the "Custom biome with a jigsaw structure" starter with
 * no problems, the Template Pool Studio's connections and a weight change, a structure
 * imported from `assets/sample-piece.nbt` (made by our own codec, see
 * `assets/make-sample-piece.ts`), the data pack export checked file by file, a placed feature
 * moved to another step (a warning only), a deliberate "Feature order cycle" error that
 * disables export and goes away on undo, the Sponge schematic export, and a second launch that
 * reopens the project with no problems.
 *
 * `worldgen.feature-order` compares project biomes with each other, and the starter has one
 * biome, so the spec first adds a second biome (the "Temperate forest biome" template, which
 * lists `minecraft:freeze_top_layer` in the top layer modification step and
 * `minecraft:lake_lava_underground` before `minecraft:lake_lava_surface` in the lakes step, as
 * the starter's biome does). Moving `minecraft:freeze_top_layer` to the vegetal decoration step
 * in the starter's biome through the Biome Studio (added to the vegetal step, then removed from
 * the top layer step) is legal in the game and reports only a `worldgen.feature-step-differs`
 * warning, which leaves export enabled. Moving the first lakes feature down in the starter's
 * biome lists the two lakes features in opposite orders in one step: a real cycle, and the
 * `worldgen.feature-order` error.
 *
 * Preview and WebGL are unavailable headless, so nothing here asserts a render.
 */

import { mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, relative } from 'node:path';
import { strFromU8, unzipSync } from 'fflate';
import { expect, type Locator, type Page, test } from 'playwright/test';
import { appDir, type LaunchedApp, launchApp, openDockTab, outputDir } from './fixtures';

/** The project folder name; a new project's namespace is derived from it. */
const NAMESPACE = 'amber_e2e';

const BIOME_ID = `${NAMESPACE}:amber_woods`;
const SECOND_BIOME_ID = `${NAMESPACE}:oak_glade`;
const CENTRE_POOL_ID = `${NAMESPACE}:hamlet/centre`;
const STREETS_POOL_ID = `${NAMESPACE}:hamlet/streets`;
const IMPORTED_ID = `${NAMESPACE}:sample-piece`;
/** The placed feature moved between steps. */
const MOVED_FEATURE = 'minecraft:freeze_top_layer';
/** The two placed features both biomes list in the lakes step, in this order. */
const LAKE_FEATURES = ['minecraft:lake_lava_underground', 'minecraft:lake_lava_surface'] as const;

/** The structure file the import picks (generated by `assets/make-sample-piece.ts`). */
const SAMPLE_PIECE = join(appDir, 'e2e', 'assets', 'sample-piece.nbt');

let base: string | undefined;
const launches: LaunchedApp[] = [];

test.afterEach(async () => {
  for (const launched of launches.splice(0)) await launched.close();
  if (base !== undefined) rmSync(base, { recursive: true, force: true });
  base = undefined;
});

/** Every file under `dir`, as paths relative to it with `/` separators, sorted. */
function filesUnder(dir: string): string[] {
  return readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => relative(dir, join(entry.parentPath, entry.name)).replaceAll('\\', '/'))
    .sort();
}

/** `.zip` names directly in `dir`, sorted. */
function zipsIn(dir: string): string[] {
  return readdirSync(dir)
    .filter((name) => name.endsWith('.zip'))
    .sort();
}

function zipJson(files: Record<string, Uint8Array>, name: string): unknown {
  const bytes = files[name];
  if (bytes === undefined) throw new Error(`${name} is missing from the zip.`);
  return JSON.parse(strFromU8(bytes));
}

/** The status toast's text. */
function toast(window: Page): Locator {
  return window.getByTestId('status-toast-text');
}

/** The Problems panel's rows (opens the panel); `severity` narrows them. */
async function problemRows(window: Page, severity?: 'error' | 'warning'): Promise<Locator> {
  await openDockTab(window, 'problems');
  const problems = window.getByTestId('problems-panel');
  await expect(problems).toBeVisible();
  return problems.locator(
    severity === undefined
      ? '[data-testid="problem-row"]'
      : `[data-testid="problem-row"][data-severity="${severity}"]`,
  );
}

/** Asserts that the Problems panel lists nothing at all and the status bar agrees. */
async function expectNoProblems(window: Page): Promise<void> {
  await expect(await problemRows(window)).toHaveCount(0);
  await expect(window.locator('footer').getByText(/^0 error\(s\)/)).toBeVisible();
}

/** Opens the export chevron menu and returns the item `testId` (not clicked). */
async function exportItem(window: Page, testId: string): Promise<Locator> {
  await window.getByTestId('toolbar-export-menu').click();
  const item = window.getByTestId(testId);
  await expect(item).toBeVisible();
  return item;
}

/** Runs a command through the palette. */
async function runCommand(window: Page, query: string, commandId: string): Promise<void> {
  await window.keyboard.press('ControlOrMeta+Shift+P');
  const palette = window.getByTestId('command-palette');
  await expect(palette).toBeVisible();
  await palette.getByTestId('command-palette-input').fill(query);
  await palette.getByTestId(`command-${commandId}`).click();
  await expect(palette).toBeHidden();
}

test('worldgen: starter, pool connections, import .nbt, export, feature order, schematics, reopen', async () => {
  base = mkdtempSync(join(tmpdir(), 'msm-worldgen-'));
  const folders = {
    projectDir: join(base, NAMESPACE),
    outDir: join(base, 'out'),
    msmHome: join(base, 'msm-home'),
  };
  mkdirSync(outputDir, { recursive: true });

  // First launch: a project from the worldgen starter. --------------------------------------
  const first = await launchApp({ pickFiles: [SAMPLE_PIECE], reuse: folders });
  launches.push(first);
  const { window } = first;
  await window.waitForLoadState('domcontentloaded');

  await window.getByTestId('toolbar-new-menu').click();
  await window.getByTestId('toolbar-new-from-starter').click();
  const newProject = window.getByTestId('new-project-dialog');
  await expect(newProject).toBeVisible();
  const starter = newProject.getByTestId('starter-picker').getByTestId('starter-worldgen_pack');
  await expect(starter).toBeVisible();
  await starter.check();
  await newProject.getByTestId('new-project-dialog-submit').click();
  await expect(newProject).toBeHidden();
  await expect(toast(window)).toContainText(
    `New project from "Custom biome with a jigsaw structure": ${folders.projectDir}`,
  );
  for (const id of [BIOME_ID, CENTRE_POOL_ID, `${NAMESPACE}:hamlet`, `${NAMESPACE}:hamlets`]) {
    await expect(window.getByTestId(`element-row-${id}`)).toBeVisible();
  }
  await expectNoProblems(window);

  // Template Pool Studio: connections to project pools, then a weight change. ---------------
  await window.getByTestId(`element-row-${CENTRE_POOL_ID}`).click();
  const pool = window.getByTestId('pool-studio');
  await expect(pool).toBeVisible();
  const connection = pool.getByTestId('pool-connection-0');
  await expect(connection).toContainText(`${NAMESPACE}:hamlet/centre_hut`);
  await expect(connection).toContainText(STREETS_POOL_ID);
  const status = connection.locator('[data-status]');
  await expect(status).toHaveAttribute('data-status', 'project');
  await expect(status).toHaveText('In project');
  await expect(pool.locator('[data-status="missing"]')).toHaveCount(0);
  const weight = pool.getByTestId('pool-piece-0-weight');
  await expect(weight).toHaveValue('1');
  await weight.fill('3');
  await expect(weight).toHaveValue('3');

  // Import a structure through the palette (File > Import Structure… in the menu bar). ------
  await runCommand(window, 'import structure', 'importStructure');
  const importDialog = window.getByTestId('import-files-dialog');
  await expect(importDialog).toBeVisible();
  await expect(importDialog.getByTestId('import-files-namespace')).toHaveValue(NAMESPACE);
  await expect(importDialog.getByTestId('import-files-importers')).toContainText('.nbt');
  await importDialog.getByTestId('import-files-dialog-submit').click();
  await expect(importDialog).toBeHidden();
  const structures = window.getByRole('region', { name: `${NAMESPACE} Structures` });
  const importedRow = structures.getByTestId(`element-row-${IMPORTED_ID}`);
  await expect(importedRow).toBeVisible();
  await importedRow.click();
  const structureStudio = window.getByTestId('structure-studio');
  await expect(structureStudio).toBeVisible();
  await expect(structureStudio.getByTestId('structure-jigsaw-0')).toBeVisible();
  await expect(structureStudio.getByTestId('structure-jigsaw-1')).toHaveCount(0);
  await expect(structureStudio.getByTestId('structure-summary')).toContainText('3');
  await expectNoProblems(window);

  // Export the data pack and check the files. -----------------------------------------------
  const dataItem = await exportItem(window, 'export-data-zip');
  await expect(dataItem).not.toHaveAttribute('data-disabled', /.*/);
  await dataItem.click();
  await expect.poll(() => zipsIn(folders.outDir), { timeout: 20_000 }).toHaveLength(1);
  const [zipName] = zipsIn(folders.outDir);
  if (zipName === undefined) throw new Error('No data pack zip.');
  const files = unzipSync(new Uint8Array(readFileSync(join(folders.outDir, zipName))));
  const names = Object.keys(files);
  expect(names).toContain('pack.mcmeta');
  for (const piece of ['hamlet/centre_hut', 'hamlet/street', 'hamlet/lamp', 'sample-piece']) {
    expect(names).toContain(`data/${NAMESPACE}/structure/${piece}.nbt`);
  }
  // Gzip signature on the imported template.
  const nbt = files[`data/${NAMESPACE}/structure/sample-piece.nbt`];
  expect(Array.from(nbt?.subarray(0, 2) ?? [])).toEqual([0x1f, 0x8b]);
  expect(names).toContain(`data/${NAMESPACE}/worldgen/biome/amber_woods.json`);
  expect(names).toContain(`data/${NAMESPACE}/worldgen/structure_set/hamlets.json`);
  const centre = zipJson(files, `data/${NAMESPACE}/worldgen/template_pool/hamlet/centre.json`) as {
    elements?: { weight?: number }[];
  };
  expect(centre.elements?.[0]?.weight).toBe(3);
  rmSync(join(folders.outDir, zipName));

  // A second biome, then a step warning and a feature order error. --------------------------
  await window.getByTestId('toolbar-add-element').click();
  const newElement = window.getByTestId('new-element-dialog');
  await expect(newElement).toBeVisible();
  await newElement.getByTestId('new-element-filter').fill('temperate forest');
  const forest = newElement.getByTestId('template-biome_temperate_forest');
  await expect(forest).toBeVisible();
  await forest.check();
  await expect(newElement.getByTestId('new-element-namespace')).toHaveValue(NAMESPACE);
  await newElement.getByTestId('new-element-name').fill('oak_glade');
  await newElement.getByTestId('new-element-dialog-submit').click();
  await expect(newElement).toBeHidden();
  await expect(window.getByTestId(`element-row-${SECOND_BIOME_ID}`)).toBeVisible();
  // An unreachable biome is only a warning: still no errors.
  await expect(await problemRows(window, 'error')).toHaveCount(0);

  await window.getByTestId(`element-row-${BIOME_ID}`).click();
  const biome = window.getByTestId('biome-studio');
  await expect(biome).toBeVisible();
  const vegetal = biome.getByTestId('biome-step-9');
  const topLayer = biome.getByTestId('biome-step-10');
  await expect(
    topLayer.getByLabel('Top layer modification features 1', { exact: true }),
  ).toHaveValue(MOVED_FEATURE);
  await vegetal.getByLabel('New entry in Vegetal decoration features').fill(MOVED_FEATURE);
  await vegetal.getByRole('button', { name: 'Add to Vegetal decoration features' }).click();
  await topLayer.getByRole('button', { name: 'Remove Top layer modification features 1' }).click();
  await expect(topLayer.getByText('None.')).toBeVisible();

  // A placed feature in different steps is legal: a warning, and export stays enabled.
  const stepWarnings = (await problemRows(window, 'warning')).and(
    window.locator('[data-code="worldgen.feature-step-differs"]'),
  );
  await expect(stepWarnings).toHaveCount(1);
  await expect(stepWarnings.first()).toContainText(MOVED_FEATURE);
  await expect(stepWarnings.first()).toContainText('placement seed');
  const errors = await problemRows(window, 'error');
  await expect(errors).toHaveCount(0);
  const stillEnabled = await exportItem(window, 'export-data-zip');
  await expect(stillEnabled).not.toHaveAttribute('data-disabled', /.*/);
  await window.keyboard.press('Escape');

  // Undo the removal and the addition: no step warning any more. ----------------------------
  await window.getByTestId('toolbar-undo').click();
  await expect(
    topLayer.getByLabel('Top layer modification features 1', { exact: true }),
  ).toHaveValue(MOVED_FEATURE);
  await window.getByTestId('toolbar-undo').click();
  await expect(stepWarnings).toHaveCount(0);
  await expect(errors).toHaveCount(0);

  // Two lakes features in opposite order to the second biome in one step: a real cycle. ----
  const lakes = biome.getByTestId('biome-step-1');
  await expect(lakes.getByLabel('Lakes features 1', { exact: true })).toHaveValue(LAKE_FEATURES[0]);
  await expect(lakes.getByLabel('Lakes features 2', { exact: true })).toHaveValue(LAKE_FEATURES[1]);
  await lakes.getByRole('button', { name: 'Move Lakes features 1 down' }).click();
  await expect(lakes.getByLabel('Lakes features 1', { exact: true })).toHaveValue(LAKE_FEATURES[1]);

  await expect(errors.first()).toBeVisible();
  await expect(errors).toHaveCount(1);
  await expect(errors.first()).toHaveAttribute('data-code', 'worldgen.feature-order');
  await expect(errors.first()).toContainText('Feature order cycle');
  for (const feature of LAKE_FEATURES) await expect(errors.first()).toContainText(feature);
  const blocked = await exportItem(window, 'export-data-zip');
  await expect(blocked).toHaveAttribute('data-disabled', /.*/);
  await expect(window.getByTestId('export-data-zip-reason')).toContainText(/Fix \d+ error/);
  await window.keyboard.press('Escape');

  // Undo the move: export is enabled again. -------------------------------------------------
  await window.getByTestId('toolbar-undo').click();
  await expect(errors).toHaveCount(0);
  const enabled = await exportItem(window, 'export-data-zip');
  await expect(enabled).not.toHaveAttribute('data-disabled', /.*/);
  await window.keyboard.press('Escape');
  // And the second biome goes too, back to no problems at all.
  await window.getByTestId('toolbar-undo').click();
  await expect(window.getByTestId(`element-row-${SECOND_BIOME_ID}`)).toHaveCount(0);
  await expectNoProblems(window);

  // Export the structures as Sponge schematics. ---------------------------------------------
  // The submenu is driven by keyboard: Playwright's pointer jumps out of Radix's grace area
  // between the submenu trigger and its content, which closes the submenu mid-click.
  await window.getByTestId('toolbar-export-menu').click();
  const more = window.getByTestId('export-more');
  await expect(more).toBeVisible();
  await more.focus();
  await window.keyboard.press('ArrowRight');
  const schematics = window.getByTestId('export-schematics');
  await expect(schematics).toBeVisible();
  await expect(schematics).not.toHaveAttribute('data-disabled', /.*/);
  await schematics.focus();
  await window.keyboard.press('Enter');
  await expect(toast(window)).toContainText('Exported 4 schematic(s)');
  const schemFiles = filesUnder(folders.outDir).filter((name) => name.endsWith('.schem'));
  expect(schemFiles).toHaveLength(4);
  expect(schemFiles.some((name) => name.endsWith('sample-piece.schem'))).toBe(true);
  expect(schemFiles.some((name) => name.endsWith('centre_hut.schem'))).toBe(true);

  await window.screenshot({ path: join(outputDir, 'worldgen-path.png') });

  // Save, so closing does not prompt to discard.
  await window.getByTestId('toolbar-save').click();
  await expect(window.locator('footer').getByText('Saved', { exact: true })).toBeVisible();
  await first.close();
  launches.splice(0);

  // Second launch: reopen, no problems, the import and the weight are kept. -----------------
  const second = await launchApp({ reuse: folders });
  launches.push(second);
  const w2 = second.window;
  await w2.waitForLoadState('domcontentloaded');
  await w2.getByTestId('toolbar-open-project').click();
  await expect(w2.getByTestId(`element-row-${IMPORTED_ID}`)).toBeVisible();
  await expect(w2.getByTestId(`element-row-${SECOND_BIOME_ID}`)).toHaveCount(0);
  await w2.getByTestId(`element-row-${CENTRE_POOL_ID}`).click();
  await expect(w2.getByTestId('pool-studio').getByTestId('pool-piece-0-weight')).toHaveValue('3');
  await expectNoProblems(w2);
  await w2.screenshot({ path: join(outputDir, 'worldgen-path-reopened.png') });
});
