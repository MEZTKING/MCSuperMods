"""B537b: turns the runtime's habit, phase and bucket classes into the eject's templates.

Run from the repository root: python3 docs/reference/eject/b537b-mob-templates/gen-mob-templates.py
Writes packages/targets/mc-26.3/src/java-project/templates/mob-habits-java.ts. Reference only (not run by CI);
the targets test `boats-and-mobs.test.ts` compares the generated classes with the runtime line by line.
"""
import re

RT = 'engine-mod/src/main/java/dev/mcsupermods/runtime/'
OUT = 'packages/targets/mc-26.3/src/java-project/templates/mob-habits-java.ts'


def read(path):
    return open(RT + path).read()


def strip_dev_imports(src):
    return '\n'.join(l for l in src.split('\n') if not l.startswith('import dev.mcsupermods'))


def body_of(src, header, pkgvar='entityPackage'):
    src = re.sub(r'^package [^;]+;', 'package @@PKG@@;', src, count=1, flags=re.M)
    text = '// Generated by MCSuperMods: ' + header + '\n' + src
    text = text.replace('\\', '\\\\').replace('`', '`').replace('${', '\\${')
    return text.replace('@@PKG@@', '${' + pkgvar + '}')


def add_imports(src, imports):
    lines = src.split('\n')
    at = max(i for i, l in enumerate(lines) if l.startswith('import '))
    for imp in reversed(imports):
        lines.insert(at + 1, 'import ' + imp + ';')
    return '\n'.join(lines)


def ts_fn(name, doc, body, modid=False):
    params = 'entityPackage: string' + (', modId: string' if modid else '')
    return f'/** {doc} */\nexport function {name}({params}): string {{\n  return `{body}`;\n}}\n'


def goal(file, header, extra=None):
    src = strip_dev_imports(read('goals/' + file))
    src = re.sub(r'\bGoal\.(Roost|PlayDead|CollectItems|DigItems|Barter)\b', r'HabitGoal.\1', src)
    if extra:
        src = extra(src)
    return src


def habit_goal_import(src):
    # The runtime imports its Goal records by nested name; the eject's are HabitGoal's.
    for rec in ['Roost', 'CollectItems', 'DigItems']:
        if re.search(r'\b' + rec + r'\b', src):
            src = add_imports(src, ['@@PKG@@.HabitGoal.' + rec])
    return src


def phase(src):
    src = src.replace('private final MobMovement movement;', 'private final Charging movement;')
    src = src.replace('MobMovement movement, double speed', 'Charging movement, double speed')
    src = src.replace(
        'public class PhaseChargeGoal extends Goal {\n',
        'public class PhaseChargeGoal extends Goal {\n'
        '    /** The mob the goal charges with: it passes through blocks while charging. */\n'
        '    public interface Charging {\n'
        '        void setCharging(boolean charging);\n'
        '    }\n\n',
        1)
    return src


def habits():
    src = strip_dev_imports(read('registry/mob/MobHabits.java'))
    src = re.sub(r'\bGoal\.(Roost|PlayDead|CollectItems|DigItems|Barter)\b', r'HabitGoal.\1', src)
    src = src.replace(
        '    private final MsmMob mob;\n',
        '    private static final Logger LOGGER = LoggerFactory.getLogger("@@MODID@@");\n\n'
        '    private final PathfinderMob mob;\n'
        '    private final String id;\n'
        '    private final EntityDataAccessor<Boolean> roostingData;\n'
        '    private final EntityDataAccessor<Boolean> playingDeadData;\n'
        '    private final boolean flies;\n', 1)
    a = src.index('    MobHabits(MsmMob mob, EntityDefinition definition) {')
    b = src.index('    /** Registers the habits\' shared listeners')
    c = src.index('    /** Matches block states of the listed blocks')
    ctor = '''    /**
     * The habits of {@code mob} ({@code id} for the log): its synched roosting and playing dead flags, whether its mode
     * flies, and the first goal of each habit ({@code null} without it).
     */
    public MobHabits(PathfinderMob mob, String id, EntityDataAccessor<Boolean> roostingData,
            EntityDataAccessor<Boolean> playingDeadData, boolean flies, HabitGoal.Roost roost, HabitGoal.PlayDead playDead,
            HabitGoal.CollectItems collect, HabitGoal.DigItems dig, HabitGoal.Barter barter) {
        this.mob = mob;
        this.id = id;
        this.roostingData = roostingData;
        this.playingDeadData = playingDeadData;
        this.flies = flies;
        this.roost = roost;
        this.playDead = playDead;
        this.collect = collect;
        this.dig = dig;
        this.barter = barter;
        this.barterItem = barter == null ? s -> false : ofItems(List.of(barter.item()));
        this.digBlock = dig == null ? s -> false : ofBlocks(dig.digBlocks());
    }

    /** Matches item stacks of the listed items; an entry starting with {@code #} is an item tag (the runtime's MobGoals.ofItems). */
    public static Predicate<ItemStack> ofItems(List<String> items) {
        Set<Identifier> ids = new java.util.HashSet<>();
        List<TagKey<Item>> tags = new java.util.ArrayList<>();
        for (String entry : items) {
            if (entry.startsWith("#")) {
                tags.add(TagKey.create(Registries.ITEM, Identifier.parse(entry.substring(1))));
            } else {
                ids.add(Identifier.parse(entry));
            }
        }
        return stack -> !stack.isEmpty() && (ids.contains(BuiltInRegistries.ITEM.getKey(stack.getItem()))
                || tags.stream().anyMatch(stack::is));
    }

'''
    src = src[:a] + ctor + src[c:]
    del b
    src = src.replace('return mob.asMob();', 'return mob;')
    src = src.replace('mob.roostingData()', 'roostingData')
    src = src.replace('mob.playingDeadData()', 'playingDeadData')
    src = src.replace('mob.driver().movement().mode().flies()', 'flies')
    src = src.replace(
        'MsmRuntime.LOGGER.warn("[{}] {}: unknown loot table {}; the habit drops nothing", MsmRuntime.MOD_ID, mob.definitionId(), table);',
        'LOGGER.warn("{}: unknown loot table {}; the habit drops nothing", id, table);')
    # Called from the generated entity class in the same package; public for clarity.
    for m in ['void hurtServer(', 'InteractionResult mobInteract(', 'void customServerAiStep(', 'void tick()', 'void die()',
              'void addAdditionalSaveData(', 'void readAdditionalSaveData(']:
        src = src.replace('\n    ' + m, '\n    public ' + m)
    src = add_imports(src, ['net.minecraft.network.syncher.EntityDataAccessor', 'net.minecraft.world.item.Item',
                            'org.slf4j.Logger', 'org.slf4j.LoggerFactory'])
    return src


def dry_bucket():
    src = read('registry/mob/MobBuckets.java')
    a = src.index('    /**\n     * The bucket of a mob that lives without water')
    end = src.rindex('}')
    inner = src[a:end].rstrip() + '\n'
    inner = '\n'.join(l[4:] if l.startswith('    ') else l for l in inner.split('\n'))
    inner = inner.replace('public static final class DryBucketItem', 'public class DryBucketItem')
    head = src[:src.index('/**\n * ')] if '/**\n * ' in src else src[:src.index('public final class')]
    head = strip_dev_imports(head)
    return head + inner


def storage():
    src = strip_dev_imports(read('registry/mob/MobStorage.java'))
    src = src.replace('StorageParser.Storage', 'Storage')
    src = src.replace(
        '    private final MsmMob mob;\n    private final EntityDefinition definition;\n',
        '    private final PathfinderMob mob;\n    /** Whether the mob has {@code msm:tameable}. */\n    private final boolean tameable;\n', 1)
    src = src.replace(
        '    MobStorage(MsmMob mob, EntityDefinition definition) {\n        this.mob = mob;\n        this.definition = definition;\n'
        '        this.storage = definition == null ? null : definition.components().storage().orElse(null);\n',
        '    /** The store of {@code mob} ({@code tameable}: only its owner opens it once tamed); {@code storage} null for none. */\n'
        '    public MobStorage(PathfinderMob mob, boolean tameable, Storage storage) {\n        this.mob = mob;\n'
        '        this.tameable = tameable;\n        this.storage = storage;\n', 1)
    src = src.replace('return mob.asMob();', 'return mob;')
    src = src.replace('definition.components().tameable().isPresent()', 'tameable')
    for m in ['boolean stillValid(', 'InteractionResult mobInteract(', 'void die()', 'void addAdditionalSaveData(',
              'void readAdditionalSaveData(']:
        src = src.replace('\n    ' + m, '\n    public ' + m)
    src = src.replace(
        'public final class MobStorage {\n',
        'public final class MobStorage {\n'
        '    /**\n     * {@code msm:storage} with every default resolved (the runtime\'s {@code StorageParser.Storage}).\n     */\n'
        '    public record Storage(int rows, boolean needsChest, Optional<Identifier> openSound, Optional<Identifier> closeSound) {\n'
        '        /** The number of slots. */\n        public int slots() {\n            return rows * 9;\n        }\n    }\n\n', 1)
    return src


