def rep(src, old, new, count=1):
    """Replaces {@code old} in {@code src}, failing when the runtime source no longer has it."""
    if old not in src:
        raise SystemExit('runtime source changed; not found: ' + old[:120])
    return src.replace(old, new) if count == 0 else src.replace(old, new, count)


def no_links(src):
    # The runtime's javadoc links name classes the eject does not have.
    return src.replace('{@link ', '{@code ')


def trader_names(src):
    src = src.replace('TraderParser.Trader', 'Trader')
