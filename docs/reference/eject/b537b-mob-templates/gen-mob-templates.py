def main():
    parts = ['''/**
 * The shared mob classes of batch 2 in an ejected project (ADR 0109 D1, D3, D4; ADR 0112 D3; B537b), generated by
 * `docs/reference/eject/b537b-mob-templates/gen-mob-templates.py` from the runtime's `registry/mob/MobHabits`, the
 * goals in `goals/` (`SwoopGoal`, `RoostGoal`, `CollectItemsGoal`, `DigForItemsGoal`, `PlayDeadGoal`,
 * `BarterGoal`, `PhaseChargeGoal`), `MobBuckets.DryBucketItem` and `MobStorage`: the runtime's parsed goal records become
 * `HabitGoal`'s, the `MsmMob` adapter the generated entity class and its synched flags, `MobMovement` the
 * `PhaseChargeGoal.Charging` the entity implements, and the logger the mod's. The targets tests compare the code lines
 * with the runtime sources. Minecraft 26.3, Mojang names.
 *
 * @packageDocumentation
 */
''']
    parts.append('/** `entity/HabitGoal.java`: the habit goal records. */\nexport function habitGoalJava(entityPackage: string): string {\n  return `' + HABIT_GOAL.replace('`', '`') + '`;\n}\n')
    hab = body_of(habits(), "msm_runtime's MobHabits (registry/mob) as a plain class.").replace('@@MODID@@', '${modId}')
    parts.append(ts_fn('mobHabitsJava', '`entity/MobHabits.java`: the runtime\'s `MobHabits`.', hab, modid=True))
    goals = [
        ('swoopGoalJava', 'SwoopGoal.java', None),
        ('roostGoalJava', 'RoostGoal.java', habit_goal_import),
        ('collectItemsGoalJava', 'CollectItemsGoal.java', habit_goal_import),
        ('digForItemsGoalJava', 'DigForItemsGoal.java', habit_goal_import),
        ('playDeadGoalJava', 'PlayDeadGoal.java', None),
        ('barterGoalJava', 'BarterGoal.java', None),
        ('phaseChargeGoalJava', 'PhaseChargeGoal.java', phase),
    ]
    for fn, file, extra in goals:
        src = goal(file, None, extra)
        body = body_of(src, "msm_runtime's " + file[:-5] + " (goals) as a plain class.")
        parts.append(ts_fn(fn, '`entity/' + file + '`: the runtime\'s `' + file[:-5] + '`.', body))
    dry = body_of(dry_bucket(), "msm_runtime's MobBuckets.DryBucketItem (registry/mob) as a plain class.")
    parts.append(ts_fn('dryBucketItemJava', '`entity/DryBucketItem.java`: the runtime\'s `MobBuckets.DryBucketItem`.', dry))
    sto = body_of(storage(), "msm_runtime's MobStorage (registry/mob) as a plain class.")
    parts.append(ts_fn('mobStorageJava', '`entity/MobStorage.java`: the runtime\'s `MobStorage`.', sto))
    open(OUT, 'w').write('\n'.join(parts))


main()
