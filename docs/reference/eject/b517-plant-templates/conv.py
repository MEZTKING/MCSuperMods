import sys, re, json
# usage: conv.py runtimeFile renames.json fnName pkgVar header > out
src=open(sys.argv[1]).read()
ren=json.load(open(sys.argv[2]))
fn=sys.argv[3]; pkgvar=sys.argv[4]; header=sys.argv[5]
for a,b in ren: src=src.replace(a,b)
lines=src.split('\n')
out=[]
for l in lines:
    if l.startswith('package '):
        out.append('package ${'+pkgvar+'};'); continue
    if l.startswith('import dev.mcsupermods'): continue
    out.append(l)
body='\n'.join(out).replace('\\','\\\\').replace('`','\\`').replace('${'+pkgvar+'}','@@PKG@@').replace('${','\\${').replace('@@PKG@@','${'+pkgvar+'}')
print(f"export function {fn}({pkgvar}: string): string {{\n  return `// Generated by MCSuperMods: {header}\n{body}`;\n}}\n")
