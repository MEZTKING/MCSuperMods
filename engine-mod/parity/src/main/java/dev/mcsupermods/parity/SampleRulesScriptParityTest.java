/**
 * Behaviour parity of the sample rules that need a script ({@code msm_sample_rules:rules/<book>}, generated by Rules,
 * ADR 0082), on content jars only: scripts are not part of the Java project eject (ADR 0033), so this class has its own
 * name and filter ({@code --gametest-filter msm_parity_tests:sample_rules_script_*}), which the ejected run's {@code
 * sample_rules_parity_test_*} does not match. Black-box like {@link SampleRulesParityTest}: a real player's uses, its
 * inventory and effects, the packets it receives, the items in the world and the server's weather.
 *
 * <ul>
 *   <li>{@code lucky_block_rules}, "Try your luck": only while sneaking; the player counter {@code lucky_uses} (saved in
 *       {@code player.data} as {@code rules.counter.lucky_uses}) counts up, read back through the chat line {@code You
 *       have used the lucky block N times.}; a Ruby and the level-up sound with a 50 per cent chance, else {@code No luck
 *       this time.} above the hotbar. The chance is {@code Math.random()}, so 200 uses must give 70 to 130 Rubies.</li>
 *   <li>{@code rally_horn_rules}, "Rally the players nearby" ({@code msm:on_use}, 40-tick cooldown): Speed for 200 ticks
 *       (amplifier 0) to every player within 16 blocks, none to a player 30 blocks away; 40 ticks later the user is told
 *       {@code The rally is over.}</li>
 *   <li>{@code world_rules}, "Stone sometimes hides a ruby": breaking Stone drops a Ruby with a 20 per cent chance (200
 *       breaks must give 20 to 60); other blocks never. "No rain in the day" ({@code server.tick} every 200 ticks): rain
 *       stops within 201 ticks in the day, and is still falling after 201 ticks at night (time 18000). "Welcome" has no
 *       server-side readback beyond packets sent at a real join, so it is left to the in-game check.</li>
 * </ul>
 */
public class SampleRulesScriptParityTest {
    private static final Identifier LEVEL_UP = Identifier.withDefaultNamespace("entity.player.levelup");
    private static final Pattern LUCKY_COUNT = Pattern.compile("You have used the lucky block (\\d+) times\\.");
    private static final String NO_LUCK = "No luck this time.";
    private static final String RALLY_OVER = "The rally is over.";
    private static final String RAIN_STOPS = "The rain stops. Time of day: ";
    private static final int LUCKY_USES = 200;
    private static final int STONE_BREAKS = 200;

    /** Runs {@code command} as the server in the test level; returns its result (-1 when it failed). */
    private static int command(GameTestHelper helper, String command) {
        ServerLevel level = helper.getLevel();
        int[] result = {-1};
        CommandSourceStack source = level.getServer().createCommandSourceStack().withLevel(level)
                .withPosition(Vec3.atBottomCenterOf(helper.absolutePos(AT))).withSuppressedOutput()
                .withCallback((success, value) -> result[0] = success ? value : -1);
        level.getServer().getCommands().performPrefixedCommand(source, command);
        return result[0];
    }

    /** The test level's time of day, 0 to 23999, as the script API's {@code dayTime} reads it. */
    private static long dayTime(ServerLevel level) {
        long ticks = level.dimensionType().defaultClock().isPresent() ? level.getDefaultClockTime() : level.getOverworldClockTime();
        return Math.floorMod(ticks, 24000L);
    }

    /** What "Try your luck" sent: the counts of its chat lines in order, the level-up sounds and the no-luck lines. */
    private record LuckyPackets(List<Integer> counts, int levelUps, int noLuck) {}

    private static LuckyPackets lucky(ParityEars ears) {
        List<Integer> counts = new ArrayList<>();
        int levelUps = 0;
        int noLuck = 0;
        for (Packet<?> packet : ears.packets()) {
            switch (packet) {
                case ClientboundSystemChatPacket chat when !chat.overlay() -> {
                    Matcher m = LUCKY_COUNT.matcher(chat.content().getString());
                    if (m.matches()) {
                        counts.add(Integer.parseInt(m.group(1)));
                    }
                }
                case ClientboundSystemChatPacket chat when NO_LUCK.equals(chat.content().getString()) -> noLuck++;
                case ClientboundSetActionBarTextPacket bar when NO_LUCK.equals(bar.text().getString()) -> noLuck++;
                case ClientboundSoundPacket sound when LEVEL_UP.equals(sound.getSound().value().location()) -> levelUps++;
                case ClientboundSoundEntityPacket sound when LEVEL_UP.equals(sound.getSound().value().location()) -> levelUps++;
                default -> {}
            }
        }
        return new LuckyPackets(counts, levelUps, noLuck);
    }

    private static List<String> systemLines(ParityEars ears) {
        List<String> out = new ArrayList<>();
        for (String line : ears.read()) {
            if (line.startsWith("system ")) {
                out.add(line.substring("system ".length()));
            }
        }
        return out;
    }

    // Try your luck

    /** Standing up, the Lucky Block does nothing: no Ruby, no line, no sound, no counter. */
    @GameTest
    public void luckyBlockDoesNothingStandingUp(GameTestHelper helper) {
        helper.setBlock(AT, block(helper, "lucky_block"));
        Item ruby = item(helper, "ruby");
        try (ParityEars ears = new ParityEars(helper, AT.west(), GameType.SURVIVAL, "msm-lucky-standing")) {
            ears.packets();
            for (int i = 0; i < 20; i++) {
                use(helper, ears.player, AT);
            }
            LuckyPackets sent = lucky(ears);
            helper.assertValueEqual(count(ears.player, ruby), 0, "rubies after 20 uses standing up");
            helper.assertValueEqual(sent, new LuckyPackets(List.of(), 0, 0), "what the uses standing up sent");

            // The counter was not touched: the first use while sneaking counts 1.
            ears.player.setShiftKeyDown(true);
            use(helper, ears.player, AT);
            helper.assertValueEqual(lucky(ears).counts(), List.of(1), "counts after the first use while sneaking");
        }
        helper.succeed();
    }

    /**
     * Sneaking, each use adds 1 to the player's counter (read back through the chat line, 1 to 200 in order) and gives a
     * Ruby with the level-up sound or the no-luck line; 200 uses give 70 to 130 Rubies (Bin(200, 0.5), about 4.2 standard
     * deviations each way).
     */
    @GameTest
    public void luckyBlockSneakingCountsAndPaysAboutHalf(GameTestHelper helper) {
        helper.setBlock(AT, block(helper, "lucky_block"));
        Item ruby = item(helper, "ruby");
        try (ParityEars ears = new ParityEars(helper, AT.west(), GameType.SURVIVAL, "msm-lucky-sneaking")) {
            ears.player.setShiftKeyDown(true);
            ears.packets();
            // A Ruby lands in the empty main hand, and a sneaking player holding something does not use blocks
            // (vanilla's secondary use), so the Rubies are taken away after each use and counted.
            int rubies = 0;
            for (int i = 0; i < LUCKY_USES; i++) {
                use(helper, ears.player, AT);
                rubies += count(ears.player, ruby);
                for (int slot = 0; slot < ears.player.getInventory().getContainerSize(); slot++) {
                    if (ears.player.getInventory().getItem(slot).is(ruby)) {
                        ears.player.getInventory().setItem(slot, ItemStack.EMPTY);
                    }
                }
            }
            helper.assertValueEqual(count(ears.player, ruby), 0, "Rubies left after taking them away");
            LuckyPackets sent = lucky(ears);
            List<Integer> expected = new ArrayList<>();
            for (int i = 1; i <= LUCKY_USES; i++) {
                expected.add(i);
            }
            helper.assertValueEqual(sent.counts(), expected, "the counter's chat lines");
            helper.assertTrue(rubies >= 70 && rubies <= 130, rubies + " Rubies from " + LUCKY_USES + " uses (70 to 130 expected)");
            helper.assertValueEqual(sent.levelUps(), rubies, "level-up sounds (one per Ruby)");
            helper.assertValueEqual(sent.noLuck(), LUCKY_USES - rubies, "no-luck lines (one per use without a Ruby)");
        }
        helper.succeed();
    }

    // Rally the players nearby

    /**
     * Using the Rally Horn gives Speed (200 ticks, amplifier 0) to the user and a player 5 blocks away, not to one 30
     * blocks away; a second use within the cooldown does nothing; 40 ticks later the user alone is told the rally is over.
     */
    @GameTest(maxTicks = 100)
    public void rallyHornSpeedsPlayersNearbyAndEndsAfterTwoSeconds(GameTestHelper helper) {
        ParityEars user = new ParityEars(helper, AT, GameType.SURVIVAL, "msm-rally-user");
        ParityEars near = new ParityEars(helper, AT.east(5), GameType.SURVIVAL, "msm-rally-near");
        ParityEars far = new ParityEars(helper, AT.east(30), GameType.SURVIVAL, "msm-rally-far");
        List<ParityEars> all = List.of(user, near, far);
        Runnable close = () -> all.forEach(ParityEars::close);
        try {
            ItemStack horn = new ItemStack(item(helper, "rally_horn"));
            user.player.setItemInHand(InteractionHand.MAIN_HAND, horn);
            all.forEach(ParityEars::packets);
            user.player.gameMode.useItem(user.player, helper.getLevel(), horn, InteractionHand.MAIN_HAND);
            for (ParityEars ears : List.of(user, near)) {
                MobEffectInstance speed = ears.player.getEffect(MobEffects.SPEED);
                helper.assertTrue(speed != null, ears.player.getScoreboardName() + " has no Speed");
                helper.assertValueEqual(speed.getDuration(), 200, ears.player.getScoreboardName() + "'s Speed duration");
                helper.assertValueEqual(speed.getAmplifier(), 0, ears.player.getScoreboardName() + "'s Speed amplifier");
                helper.assertTrue(ears.read().contains("actionbar Rally!"), ears.player.getScoreboardName() + " saw no 'Rally!'");
            }
            helper.assertFalse(far.player.hasEffect(MobEffects.SPEED), "the player 30 blocks away has Speed");

            // Within the 40-tick cooldown a second use does nothing.
            near.player.removeEffect(MobEffects.SPEED);
            user.player.gameMode.useItem(user.player, helper.getLevel(), user.player.getMainHandItem(), InteractionHand.MAIN_HAND);
            helper.assertFalse(near.player.hasEffect(MobEffects.SPEED), "a use within the cooldown gave Speed again");
        } catch (RuntimeException e) {
            close.run();
            throw e;
        }
        long start = helper.getLevel().getGameTime();
        List<String> userLines = new ArrayList<>();
        List<String> nearLines = new ArrayList<>();
        helper.onEachTick(() -> {
            if (!user.player.isRemoved()) {
                userLines.addAll(systemLines(user));
                nearLines.addAll(systemLines(near));
            }
        });
        helper.runAfterDelay(39, () -> {
            try {
                helper.assertFalse(userLines.contains(RALLY_OVER), "the rally ended before 40 ticks");
            } catch (RuntimeException e) {
                close.run();
                throw e;
            }
        });
        helper.runAfterDelay(45, () -> {
            try {
                userLines.addAll(systemLines(user));
                nearLines.addAll(systemLines(near));
                helper.assertValueEqual(userLines.stream().filter(RALLY_OVER::equals).count(), 1L,
                        "'" + RALLY_OVER + "' lines to the user after " + (helper.getLevel().getGameTime() - start) + " ticks: " + userLines);
                helper.assertFalse(nearLines.contains(RALLY_OVER), "the player nearby was told the rally is over");
            } finally {
                close.run();
            }
            helper.succeed();
        });
    }

    // Stone sometimes hides a ruby

    /**
     * Breaking Stone 200 times drops 20 to 60 Rubies (Bin(200, 0.2), about 3.5 standard deviations each way) at the block;
     * breaking 50 dirt blocks drops none.
     */
    @GameTest
    public void stoneBreaksSometimesDropRubies(GameTestHelper helper) {
        Item ruby = item(helper, "ruby");
        BlockPos stone = AT;
        BlockPos dirt = AT.east(4);
        try (ParityEars ears = new ParityEars(helper, AT.west(), GameType.SURVIVAL, "msm-stone-breaker")) {
            int dirtRubies = breakAndCount(helper, ears, dirt, Blocks.DIRT, 50, ruby);
            helper.assertValueEqual(dirtRubies, 0, "Rubies from 50 dirt blocks");
            int rubies = breakAndCount(helper, ears, stone, Blocks.STONE, STONE_BREAKS, ruby);
            helper.assertTrue(rubies >= 20 && rubies <= 60, rubies + " Rubies from " + STONE_BREAKS + " Stone (20 to 60 expected)");
        }
        helper.succeed();
    }

    /** Places and breaks {@code block} at {@code rel} {@code times} times in one tick; returns the Rubies dropped there. */
    private static int breakAndCount(GameTestHelper helper, ParityEars ears, BlockPos rel, Block block, int times, Item ruby) {
        BlockPos abs = helper.absolutePos(rel);
        for (int i = 0; i < times; i++) {
            helper.setBlock(rel, block);
            helper.assertTrue(ears.player.gameMode.destroyBlock(abs), "breaking " + block + " failed");
        }
        int rubies = 0;
        for (ItemEntity drop : helper.getLevel().getEntitiesOfClass(ItemEntity.class, new AABB(abs).inflate(1.5))) {
            if (drop.getItem().is(ruby)) {
                rubies += drop.getItem().getCount();
                drop.discard();
            }
        }
        return rubies;
    }

    // No rain in the day

    /**
     * At night (18000) rain is still falling 205 ticks later; switched to day (6000) it stops within 201 ticks and every
     * player is told so with the time of day. Weather and time are the server's, so the test puts clear weather and the
     * old time back.
     */
    @GameTest(maxTicks = 500)
    public void rainStopsInTheDayButNotAtNight(GameTestHelper helper) {
        ServerLevel level = helper.getLevel();
        MinecraftServer server = level.getServer();
        WeatherData weather = server.getWeatherData();
        long oldTime = dayTime(level);
        ParityEars ears = ParityEars.listener(helper, AT);
        List<String> lines = new ArrayList<>();
        long[] dayFrom = {0};
        Runnable restore = () -> {
            server.setWeatherParameters(6000, 0, false, false);
            command(helper, "time set " + oldTime);
            ears.close();
        };
        helper.onEachTick(() -> {
            if (!ears.player.isRemoved()) {
                lines.addAll(systemLines(ears));
            }
        });
        helper.startSequence()
                .thenExecute(() -> {
                    helper.assertTrue(command(helper, "time set 18000") >= 0, "/time set 18000 failed");
                    helper.assertValueEqual(dayTime(level), 18000L, "time of day after /time set 18000");
                    server.setWeatherParameters(0, 6000, true, false);
                    helper.assertTrue(weather.isRaining(), "no rain after setting it");
                })
                .thenIdle(205)
                .thenExecute(() -> {
                    try {
                        helper.assertTrue(dayTime(level) >= 13000 && dayTime(level) < 23000, "no longer night: " + dayTime(level));
                        helper.assertTrue(weather.isRaining(), "the rain stopped at night");
                        helper.assertFalse(lines.stream().anyMatch(l -> l.startsWith(RAIN_STOPS)), "told the rain stops at night: " + lines);
                        helper.assertTrue(command(helper, "time set 6000") >= 0, "/time set 6000 failed");
                        helper.assertValueEqual(dayTime(level), 6000L, "time of day after /time set 6000");
                        dayFrom[0] = level.getGameTime();
                    } catch (RuntimeException e) {
                        restore.run();
                        throw e;
                    }
                })
                .thenWaitUntil(() -> helper.assertFalse(weather.isRaining(), "still raining in the day"))
                .thenExecute(() -> {
                    try {
                        long waited = level.getGameTime() - dayFrom[0];
                        helper.assertTrue(waited <= 201, "the rain stopped " + waited + " ticks into the day");
                        helper.assertTrue(weather.getClearWeatherTime() > 0 && weather.getClearWeatherTime() <= 6000,
                                "clear weather for " + weather.getClearWeatherTime() + " ticks (300 s expected)");
                        lines.addAll(systemLines(ears));
                        helper.assertTrue(lines.stream().anyMatch(l -> l.startsWith(RAIN_STOPS + "6")),
                                "no '" + RAIN_STOPS + "6...' line: " + lines);
                    } finally {
                        restore.run();
                    }
                })
                .thenSucceed();
    }
}
