/**
 * Behaviour phrases of the Rules plugin for the search (ADR 0124 D7; B655): what a made block,
 * item, mob or vehicle does ("a block that drops xp", "a wand that teleports you"), each as one
 * rule of the Rules catalogue with the made thing as its subject (the string `$thing`), as the
 * rule book stores it. Each behaviour applies to one sort of thing, the sort its trigger's
 * subject is, so the same phrase can name a different rule for a block and for a mob. Flow
 * answers and companion flows ("glows", "sets mobs on fire") are the library's.
 *
 * `test/search.test.ts` puts every rule, with a project subject in place of `$thing`, in a rule
 * book, validates the book against `rules.mcdoc` and compiles it with the plugin's own compiler
 * on both targets: no problem.
 */

import type { Json, JsonObject, SearchBehaviour, SearchBehaviourSubject } from '@msm/plugin-api';

/** The string a behaviour's rule names the made thing by. */
export const THING = '$thing';

/** A rule on the made thing: `when` the trigger fires, do `steps`. */
function rule(
  key: string,
  name: string,
  trigger: string,
  steps: Json[],
  options?: JsonObject,
): Json {
  const when: JsonObject = { subject: THING, trigger };
  if (options !== undefined) when.options = options;
  return { do: steps, key, name, when };
}

/** One behaviour of one sort of thing. */
function behaviour(
  id: string,
  appliesTo: SearchBehaviourSubject,
  phrases: string[],
  sentence: string,
  trigger: string,
  steps: Json[],
  options?: JsonObject,
): SearchBehaviour {
  const key = id.replace(/-/g, '_');
  return {
    appliesTo: [appliesTo],
    id,
    phrases,
    rule: rule(key, sentence.replace(/\.$/, ''), trigger, steps, options),
    sentence,
  };
}

/** Thirty seconds of an effect, to the player. */
const effect = (id: string, seconds = 30, level?: number): Json =>
  level === undefined
    ? { effect: id, seconds, step: 'give_effect' }
    : { effect: id, level, seconds, step: 'give_effect' };

/** Where the player looks, up to `distance` blocks away. */
const looking = (distance: number): Json => ({ distance, place: 'player_looking' });

