/**
 * `CHANGES-draft.md`: the change set in words, for the person who writes the curated file.
 * Generated; never edited by hand.
 *
 * @packageDocumentation
 */

import type { TargetDiff } from './diff.ts';
import type { TargetChange, TargetChangeArea } from './types.ts';

const AREAS: readonly { area: TargetChangeArea; title: string }[] = [
  { area: 'ids', title: 'Ids' },
  { area: 'formats', title: 'Data formats' },
  { area: 'commands', title: 'Commands' },
  { area: 'block-states', title: 'Block states' },
  { area: 'packs', title: 'Packs and versions' },
];

const code = (text: string): string => `\`${text.replaceAll('`', "'")}\``;
const show = (value: unknown): string =>
  typeof value === 'string' ? code(value) : code(JSON.stringify(value));

function line(c: TargetChange): string {
  const parts = [`${c.what}: ${code(c.subject)}`];
  if (c.field !== undefined) parts.push(`field ${code(c.field)}`);
  if (c.from !== undefined) parts.push(`from ${show(c.from)}`);
  if (c.to !== undefined) parts.push(`to ${show(c.to)}`);
  if (c.stillIn !== undefined) parts.push(`still in ${c.stillIn.map(code).join(', ')}`);
  parts.push(`(${c.handling})`);
  return `- ${parts.join(' ')}`;
}

/** The draft's text. */
export function draftText(diff: TargetDiff): string {
  const set = diff.changeSet;
  const out: string[] = [
    `# Changes from ${set.from} to ${set.to} (draft)`,
    '',
    "Generated by `tools/diff-targets` from both targets' vendored data; do not edit. Confirm candidates, and write sentences, hints and in-game checks, in the target's curated change file.",
    '',
    `- Pins: vanilla-mcdoc ${code(set.refs.from.mcdoc)} to ${code(set.refs.to.mcdoc)}, mcmeta ${code(set.refs.from.mcmeta)} to ${code(set.refs.to.mcmeta)}.`,
    `- Data formats compared ${diff.mcdocMode === 'gated' ? 'by resolving the newer vanilla-mcdoc export at both versions (a step between release lines)' : "by each target's own vanilla-mcdoc export (a re-pin within one release line)"}.`,
    `- Command reports: ${diff.commandFormats.before} to ${diff.commandFormats.after}.`,
    `- ${set.changes.length} changes: ${(['manual', 'auto', 'none'] as const)
      .map((h) => `${set.changes.filter((c) => c.handling === h).length} ${h}`)
      .join(', ')}.`,
    '',
  ];
  for (const { area, title } of AREAS) {
    const list = set.changes.filter((c) => c.area === area);
    if (list.length === 0) continue;
    out.push(`## ${title}`, '', ...list.map(line), '');
  }
  const candidates = set.changes.filter((c) => c.candidate !== undefined);
  if (candidates.length > 0) {
    out.push('## Candidates (unconfirmed)', '');
    for (const c of candidates) {
      const k = c.candidate as NonNullable<TargetChange['candidate']>;
      const partners =
        k.ambiguous && Array.isArray(c.to) ? c.to.map(show).join(' or ') : code(k.to);
      out.push(
        `- ${k.kind}: ${code(c.subject)}${c.field === undefined ? '' : ` ${code(c.field)}`} to ${partners}; name ${k.name}, shape ${k.shape}${k.ambiguous ? ', ambiguous' : ''}`,
      );
    }
    out.push('');
  }
  const counts = Object.entries(set.additions).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  if (counts.length > 0) {
    out.push('## Additions (counts)', '', ...counts.map(([k, n]) => `- ${code(k)}: ${n}`), '');
  }
  return `${out.join('\n')}`;
}
